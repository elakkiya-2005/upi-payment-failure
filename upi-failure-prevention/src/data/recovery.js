// Helper: overall recovery rate from the records above.
export const getRecoveryStats = () => {
  const total = recoveryRecords.length;
  const recovered = recoveryRecords.filter(
    (r) => r.recoveryStatus === "recovered"
  ).length;
  const failed = recoveryRecords.filter(
    (r) => r.recoveryStatus === "failed"
  ).length;
  const pending = total - recovered - failed;
  return {
    total,
    recovered,
    failed,
    pending,
    recoveryRate: total ? Math.round((recovered / total) * 100) : 0,
  };
};